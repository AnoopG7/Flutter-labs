class Movie {
  final String id;
  final String title;
  final String category;
  final String year;
  final double rating;
  final String duration;
  final String description;
  final String imageUrl;

  const Movie({
    required this.id,
    required this.title,
    required this.category,
    required this.year,
    required this.rating,
    required this.duration,
    required this.description,
    required this.imageUrl,
  });
}